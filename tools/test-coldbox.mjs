import assert from 'node:assert/strict';
import * as T from 'three';
import { createAdvancedColdBox, R101_REFERENCE } from '../src/coldbox-assembly.js';

globalThis.document={createElement(){return {getContext(){return null;}};}};
const root=new T.Group();
const model=createAdvancedColdBox(root,9.25,-4.95);
assert.ok(R101_REFERENCE.refrigerant.includes('Helium'));
assert.equal(model.modules.length,4);
assert.equal(model.turbines.length,2);
assert.equal(model.routes.length,7);
assert.equal(model.routeSummary.filter(q=>q.fluid==='h2').length,1);
assert.equal(model.routeSummary.filter(q=>q.fluid==='he').length,6);
for(const route of model.routeSummary)assert.ok(route.count>=2,route.name);
assert.ok(model.routes.some(r=>r.holder.name.includes('return through')));
assert.deepEqual(model.root.position.toArray(),[9.25,0,-4.95]);
assert.ok(model.shell.visible);
assert.ok(!model.inside.visible);
model.setView('cutaway');
assert.ok(!model.shell.visible&&model.inside.visible);
assert.ok(model.plumbing.visible&&!model.guides.visible);
model.setStream('he');
assert.ok(!model.paths.h2.visible&&model.paths.he.visible);
model.setStream('h2');
assert.ok(model.paths.h2.visible&&!model.paths.he.visible);
model.setStream('both');
assert.ok(model.paths.h2.visible&&model.paths.he.visible);
model.animate(.4);
model.setFlow(false);
assert.ok(model.routes.every(r=>!r.dots.visible&&!r.arrows.visible));
model.setFlow(true);
assert.ok(model.routes.every(r=>r.dots.visible&&r.arrows.visible));
model.setView('exploded');
assert.ok(model.inside.visible&&!model.plumbing.visible&&model.guides.visible);
assert.ok(model.modules.every(q=>q.obj.position.length()>0));
model.setView('cutaway');
assert.ok(model.modules.every(q=>q.obj.position.length()===0));
model.setView('shell');
assert.ok(!model.inside.visible&&model.shell.visible);
const found=new Set();
model.root.traverse(o=>{if(o.userData?.assembly)found.add(o.userData.assembly);});
for(const name of R101_REFERENCE.equipment)assert.ok(found.has(name),name);
console.log('PASS: R-101 geometry, isolated H2 and helium circuits, shell/cutaway/exploded and flow toggle');
